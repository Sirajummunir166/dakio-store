// `{name}` placeholders filled from `vars`; a missing var leaves its placeholder.
const fill = (s, vars) => (vars && typeof s === 'string'
  ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m))
  : s);

/** `tx(lang)` → `(key, vars?) => words`, English for a missing key or language. */
export function siteText(lang) {
  const d = lang === 'bn' ? BN : EN;
  return (key, vars) => fill(d[key] ?? EN[key] ?? key, vars);
}

